# --------------------------------------------------------------------------
# aircraft model
# --------------------------------------------------------------------------
class FixedWing3DOF:
    nx, nu = 6, 3

    def __init__(self):
        self.m, self.g = MASS, GRAVITY
        self.a1 = 0.5 * RHO * WING_AREA * C_D0                           # D = a1 V^2 + a2 n^2 / V^2
        self.a2 = 2.0 * K_INDUCED * (MASS * GRAVITY) ** 2 / (RHO * WING_AREA)
        self.c_stall = RHO * WING_AREA * C_L_MAX / (2.0 * MASS * GRAVITY)  # n <= c_stall V^2

    def drag(self, V, n2):
        return self.a1 * V**2 + self.a2 * n2 / V**2

    def f(self, x, u):
        """Dynamics, batched over leading dimensions."""
        V, ga, ch = x[..., 3], x[..., 4], x[..., 5]
        T, nv, nh = u[..., 0], u[..., 1], u[..., 2]
        cg, sg, cc, sc = np.cos(ga), np.sin(ga), np.cos(ch), np.sin(ch)
        D = self.drag(V, nv**2 + nh**2)
        return np.stack([V * cg * cc, V * cg * sc, V * sg,
                         (T - D) / self.m - self.g * sg,
                         self.g * (nv - cg) / V,
                         self.g * nh / (V * cg)], axis=-1)

    def jacobians(self, x, u):
        """A = df/dx (..., 6, 6), B = df/du (..., 6, 3)."""
        V, ga, ch = x[..., 3], x[..., 4], x[..., 5]
        T, nv, nh = u[..., 0], u[..., 1], u[..., 2]
        cg, sg, cc, sc = np.cos(ga), np.sin(ga), np.cos(ch), np.sin(ch)
        g, m, n2 = self.g, self.m, nv**2 + nh**2
        A = np.zeros(x.shape[:-1] + (6, 6))
        B = np.zeros(x.shape[:-1] + (6, 3))
        A[..., 0, 3], A[..., 0, 4], A[..., 0, 5] = cg * cc, -V * sg * cc, -V * cg * sc
        A[..., 1, 3], A[..., 1, 4], A[..., 1, 5] = cg * sc, -V * sg * sc, V * cg * cc
        A[..., 2, 3], A[..., 2, 4] = sg, V * cg
        A[..., 3, 3] = -(2 * self.a1 * V - 2 * self.a2 * n2 / V**3) / m
        A[..., 3, 4] = -g * cg
        A[..., 4, 3], A[..., 4, 4] = -g * (nv - cg) / V**2, g * sg / V
        A[..., 5, 3] = -g * nh / (V**2 * cg)
        A[..., 5, 4] = g * nh * sg / (V * cg**2)
        B[..., 3, 0] = 1.0 / m
        B[..., 3, 1] = -2 * self.a2 * nv / (V**2 * m)
        B[..., 3, 2] = -2 * self.a2 * nh / (V**2 * m)
        B[..., 4, 1] = g / V
        B[..., 5, 2] = g / (V * cg)
        return A, B

    def trim_controls(self, x):
        """Controls holding speed and flight-path angle, wings level."""
        V, ga = x[..., 3], x[..., 4]
        nv = np.cos(ga)
        T_av = THRUST_PLAN_FRACTION * (T_MAX + THRUST_SLOPE * V)
        T = np.clip(self.drag(V, nv**2) + self.m * self.g * np.sin(ga), 0.0, T_av)
        return np.stack([T, nv, np.zeros_like(nv)], axis=-1)


