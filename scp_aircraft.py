def load_plan(envs_file, results_file, index):
    """Load environment `index` and its saved SCP result, refusing to pair a
    plan with an environment it was not solved for."""
    from types import SimpleNamespace
    envs = load_environments(envs_file)
    with open(results_file) as f:
        r = next((r for r in json.load(f) if r["env_index"] == index), None)
    if r is None:
        raise SystemExit(f"No result for environment {index} in {results_file}.")
    if index >= len(envs):
        raise SystemExit(f"{envs_file} has only {len(envs)} environments.")
    env = envs[index]
    fp = r.get("env_fingerprint")
    if fp is None:
        print(f"Warning: {results_file} predates environment fingerprints; cannot confirm it "
              f"was solved on {envs_file}. Re-run scp_aircraft.py to be safe.")
    elif fp != env.fingerprint():
        raise SystemExit(
            f"MISMATCH: the plan for environment {index} in {results_file} was solved on a different "
            f"environment (it came from {r.get('env_file', '?')}) than environment {index} in {envs_file}.\n"
            f"Pass the same --envs file that was used when solving, or re-run scp_aircraft.py.")
    res = SimpleNamespace(x=np.array(r["x"]), u=np.array(r["u"]), flight_time=r["flight_time"],
                          status=r["status"], success=r["success"])
    return env, r, res


def plan_clearance(env, res, solver=None, steps=40):
    """Closest approach of the planned path to any obstacle surface, allowing
    for the vehicle radius (negative = the aircraft would touch it)."""
    solver = solver or AircraftSCP()
    dense = solver.propagate(np.asarray(res.x), np.asarray(res.u), res.flight_time, steps, sens=False)
    P = solver.check_points(np.asarray(res.x), dense)
    A, b = env.linearized_constraints(P)
    h = np.einsum("cmk,ck->cm", A, P) - b                     # at d = r + margin
    gn = np.maximum(np.linalg.norm(A, axis=-1), 1e-9)
    return float((h / gn).min() + env.margin)                  # add back the margin -> body clearance


def plot_result(env, res, solver):
    import matplotlib.pyplot as plt
    from envgen import plot_environment

    dense = solver.propagate(res.x, res.u, res.flight_time, 20, sens=False)
    P = solver.check_points(res.x, dense)
    ax = plot_environment(env)
    ax.plot(P[:, 0], P[:, 1], P[:, 2], "k-", lw=2, label=f"SCP ({res.status})")
    ax.legend(loc="upper left")

    t = np.linspace(0, res.flight_time, len(res.x))
    bank = np.degrees(np.arctan2(res.u[:, 2], res.u[:, 1]))
    fig, axs = plt.subplots(2, 2, figsize=(10, 6), sharex=True)
    axs[0, 0].plot(t, res.x[:, 3]); axs[0, 0].axhline(V_MIN, ls=":", c="r"); axs[0, 0].set_ylabel("V [m/s]")
    axs[0, 1].plot(t, np.degrees(res.x[:, 4])); axs[0, 1].set_ylabel("gamma [deg]")
    axs[1, 0].plot(t, bank); axs[1, 0].set_ylabel("bank [deg]"); axs[1, 0].set_xlabel("t [s]")
    axs[1, 1].plot(t, res.u[:, 0]); axs[1, 1].set_ylabel("thrust [N]"); axs[1, 1].set_xlabel("t [s]")
    fig.tight_layout()
    plt.show()


