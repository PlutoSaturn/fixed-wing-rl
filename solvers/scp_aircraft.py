#!/usr/bin/env python3
"""
scp_aircraft.py - SCP (SCvx-style) for a 3-DOF point-mass fixed-wing aircraft
on environments generated by envgen.py.

--------------------------------------------------------------------------
Aircraft model
--------------------------------------------------------------------------
State   x = (px, py, pz, V, gamma, chi)   position [m], airspeed [m/s],
                                          flight-path angle, heading [rad]
Control u = (T, n_v, n_h)                 thrust [N], load factor components
                                          in the vertical / horizontal plane
                                          (n = sqrt(n_v^2 + n_h^2), bank = atan2(n_h, n_v))

    px'    = V cos(gamma) cos(chi)
    py'    = V cos(gamma) sin(chi)
    pz'    = V sin(gamma)
    V'     = (T - D) / m - g sin(gamma)
    gamma' = g (n_v - cos(gamma)) / V
    chi'   = g n_h / (V cos(gamma))

    D = q S C_D0 + K (n m g)^2 / (q S),   q = rho V^2 / 2   (parabolic drag polar)

Using load factor components instead of (C_L, bank) keeps most limits convex:
    0 <= T <= T_MAX                                  (linear)
    ||(n_v, n_h)||_2 <= N_MAX                        (second-order cone)
    |n_h| <= tan(BANK_MAX) n_v                       (linear, also forces n_v >= 0)
    V_MIN <= V <= V_MAX,  |gamma| <= GAMMA_MAX       (linear state bounds)
    ||(n_v, n_h)||_2 <= c_stall V^2                  (lift <= C_L_MAX; nonconvex)
The stall constraint is linearized as c_stall (2 V_bar V - V_bar^2), which
underestimates V^2, so the linearized constraint is conservative.

--------------------------------------------------------------------------
SCP formulation
--------------------------------------------------------------------------
Free final time: t = sigma * tau with tau in [0, 1]; sigma (flight time) is a
decision variable. Controls are first-order hold (linear between nodes).

Each iteration:
  * Propagates the nonlinear dynamics over every interval from the reference
    nodes (multiple shooting, RK4) together with the sensitivities of the end
    state to x_k, u_k, u_{k+1} and sigma. This gives the linearized dynamics
        x_{k+1} = x_prop + Phi dx_k + Bm du_k + Bp du_{k+1} + S dsigma + nu_k
    where nu_k is a virtual control (penalized) so the subproblem is never
    infeasible because of a poor linearization.
  * Obstacle constraints are enforced at every RK4 substep inside each
    interval (not just the nodes), using the same sensitivities to express
    each intermediate position as an affine function of the variables.
  * Solves the convex subproblem with a trust region; accepts or rejects via
    the SCvx ratio test on the nonlinear merit function
        J = cost + LAMBDA_DYN * sum ||defects / x_scale||_1
                 + LAMBDA_OBS * sum (obstacle violations / POS_SCALE)
    Both penalties are on scaled quantities, so a metre of dynamics error and a
    metre of obstacle intrusion cost the same order of magnitude.

Boundary conditions: start at the environment's start position, level
flight at V_CRUISE, heading toward the goal; end at the goal position
(speed, heading free within limits). The environment's start/goal
velocities are ignored.

Cost: W_TIME * flight time + W_SMOOTH * sum ||(u_{k+1} - u_k) / u_scale||^2.

Early stopping (PTR): a start is abandoned when it stays infeasible without
meaningful progress for STALL_WINDOW iterations; a feasible trajectory is
polished for at most POLISH_ITERS iterations, or until the cost stops
improving over COST_WINDOW iterations. RK4 substeps scale with the interval
length (MAX_SUBSTEP_S) so the propagation stays numerically stable.

Environments must be at aircraft scale. For the default airframe (turn
radius about 13 m) try:
    python envgen.py --size 400 400 120 --vehicle-radius 1 --margin 2 \
                     --occupancy 0.02 0.10 --n 20 --out envs_aircraft.json

Usage
    python scp_aircraft.py --envs c172_envs.json          # solve all
    python scp_aircraft.py --envs c172_envs.json --show 0 # plot a saved plan
"""
