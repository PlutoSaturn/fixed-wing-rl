def main():
    ap = argparse.ArgumentParser(description="Run fixed-wing SCP on generated environments.")
    ap.add_argument("--envs", default=ENV_FILE)
    ap.add_argument("--out", default=RESULTS_FILE)
    ap.add_argument("--feasible-out", default=FEASIBLE_FILE)
    ap.add_argument("--max-envs", type=int, default=MAX_ENVS)
    ap.add_argument("--plot", type=int, default=PLOT_INDEX, metavar="INDEX",
                    help="solve, then re-solve and plot this environment")
    ap.add_argument("--show", type=int, default=None, metavar="INDEX",
                    help="plot a SAVED result (from --out) without solving anything")
    ap.add_argument("--verbose", action=argparse.BooleanOptionalAction, default=VERBOSE)
    args = ap.parse_args()
    warnings.filterwarnings("ignore", category=UserWarning, module="cvxpy")

    if args.show is not None:
        env, r, res = load_plan(args.envs, args.out, args.show)
        print(f"Environment {args.show}: {res.status}, flight {res.flight_time:.1f} s, "
              f"closest approach to an obstacle {plan_clearance(env, res):.1f} m")
        plot_result(env, res, AircraftSCP())
        return

    envs = load_environments(args.envs)[: args.max_envs]
    solver = AircraftSCP(verbose=args.verbose)
    results, feasible = [], []
    print(f"Solving {len(envs)} environments with {solver.name} [{AIRFRAME_NAME}] "
          f"(up to {solver.n_starts} starts each)")
    for i, env in enumerate(envs):
        res = solver.solve(env)
        print(f"  env {i:3d}  fill {env.metrics.get('occupancy_fraction', float('nan')):5.1%}  "
              f"{res.status:24s} start {len(res.attempts)}  iters {res.iterations:2d}  "
              f"{res.solve_time:6.1f}s  flight {res.flight_time:6.1f}s  margin {res.dense_min_margin:+.2f}")
        results.append({"env_index": i, "env_file": args.envs, "env_fingerprint": env.fingerprint(),
                        "solver": solver.name, **res.to_dict()})
        if res.success:
            feasible.append(env)

    with open(args.out, "w") as f:
        json.dump(results, f)
    save_environments(feasible, args.feasible_out)
    print(f"\n{len(feasible)}/{len(envs)} feasible. Results -> {args.out}, "
          f"feasible environments -> {args.feasible_out}")
    if args.plot is not None:
        plot_result(envs[args.plot], solver.solve(envs[args.plot]), solver)


if __name__ == "__main__":
    main()